"""
Execution Accuracy (EX) Evaluation Engine.

Executes candidate and gold SQL queries in a sandboxed database environment
and validates tabular result parity with support for:
- Order invariance (bag/multiset comparison) vs order-sensitive validation
- Float precision tolerances (atol, rtol)
- NULL/None/NaN canonical equivalence
- Column alias flexibility and positional mapping
- Detailed tabular diff diagnostics (missing rows, extra rows, shape mismatch)
"""

import logging
import math
from typing import Optional, Any
from dataclasses import dataclass, field
import pandas as pd
import numpy as np

from .sandbox import DatabaseSandbox
from .dataset import ExecutionExpectation

logger = logging.getLogger(__name__)


@dataclass
class ExecutionResult:
    """Detailed result of tabular execution comparison."""
    is_executed: bool
    execution_accuracy: float  # 1.0 for exact pass, 0.0 for fail
    row_overlap_score: float  # 0.0 to 1.0 soft Jaccard overlap
    candidate_row_count: int = 0
    gold_row_count: int = 0
    shape_match: bool = False
    columns_match: bool = False
    candidate_error: Optional[str] = None
    gold_error: Optional[str] = None
    missing_rows_count: int = 0
    extra_rows_count: int = 0
    diff_summary: Optional[str] = None
    candidate_sample: Optional[list[dict]] = None
    gold_sample: Optional[list[dict]] = None


class ExecutionAccuracyEvaluator:
    """
    Evaluator for checking Execution Accuracy (EX) of Text-to-SQL outputs.
    """

    def __init__(self, default_sandbox: Optional[DatabaseSandbox] = None):
        self.default_sandbox = default_sandbox

    def evaluate(
        self,
        candidate_sql: str,
        gold_sql: str,
        sandbox: Optional[DatabaseSandbox] = None,
        expectation: Optional[ExecutionExpectation] = None,
    ) -> ExecutionResult:
        """
        Execute candidate and gold SQL and verify tabular equivalence.

        Args:
            candidate_sql: SQL generated by the agent.
            gold_sql: Reference ground truth SQL query.
            sandbox: The DatabaseSandbox instance to execute in.
            expectation: ExecutionExpectation parameters.

        Returns:
            ExecutionResult with accuracy metric and diagnostics.
        """
        active_sandbox = sandbox or self.default_sandbox
        if active_sandbox is None:
            raise ValueError("No DatabaseSandbox provided for execution evaluation.")

        exp = expectation or ExecutionExpectation()

        # 1. Execute candidate query
        cand_df, cand_err = active_sandbox.execute_query(candidate_sql)
        if cand_err is not None or cand_df is None:
            return ExecutionResult(
                is_executed=False,
                execution_accuracy=0.0,
                row_overlap_score=0.0,
                candidate_error=cand_err,
                diff_summary=f"Candidate SQL execution failed: {cand_err}",
            )

        # 2. Execute gold query
        gold_df, gold_err = active_sandbox.execute_query(gold_sql)
        if gold_err is not None or gold_df is None:
            return ExecutionResult(
                is_executed=True,
                execution_accuracy=0.0,
                row_overlap_score=0.0,
                gold_error=gold_err,
                diff_summary=f"Gold SQL execution failed: {gold_err}",
            )

        # 3. Compare DataFrames
        return self.compare_dataframes(cand_df, gold_df, exp)

    def compare_dataframes(
        self,
        cand_df: pd.DataFrame,
        gold_df: pd.DataFrame,
        expectation: ExecutionExpectation,
    ) -> ExecutionResult:
        """
        Compare two DataFrames according to evaluation expectations.
        """
        cand_rows, cand_cols = cand_df.shape
        gold_rows, gold_cols = gold_df.shape

        cand_sample = cand_df.head(5).to_dict(orient="records")
        gold_sample = gold_df.head(5).to_dict(orient="records")

        # Column count mismatch
        if cand_cols != gold_cols:
            return ExecutionResult(
                is_executed=True,
                execution_accuracy=0.0,
                row_overlap_score=0.0,
                candidate_row_count=cand_rows,
                gold_row_count=gold_rows,
                shape_match=False,
                columns_match=False,
                diff_summary=(
                    f"Column count mismatch: candidate returned {cand_cols} columns "
                    f"({list(cand_df.columns)}), expected {gold_cols} columns ({list(gold_df.columns)})"
                ),
                candidate_sample=cand_sample,
                gold_sample=gold_sample,
            )

        # Empty result set parity
        if gold_rows == 0 and cand_rows == 0:
            return ExecutionResult(
                is_executed=True,
                execution_accuracy=1.0,
                row_overlap_score=1.0,
                candidate_row_count=0,
                gold_row_count=0,
                shape_match=True,
                columns_match=True,
                diff_summary="Both candidate and gold returned empty result sets (0 rows).",
                candidate_sample=[],
                gold_sample=[],
            )

        # Normalize values in DataFrames
        norm_cand = self._normalize_dataframe(cand_df, expectation)
        norm_gold = self._normalize_dataframe(gold_df, expectation)

        # Convert rows to canonical tuple representations
        cand_tuples = [self._row_to_tuple(row) for _, row in norm_cand.iterrows()]
        gold_tuples = [self._row_to_tuple(row) for _, row in norm_gold.iterrows()]

        if expectation.order_sensitive:
            # Strict ordered row comparison
            if cand_rows != gold_rows:
                return ExecutionResult(
                    is_executed=True,
                    execution_accuracy=0.0,
                    row_overlap_score=0.0,
                    candidate_row_count=cand_rows,
                    gold_row_count=gold_rows,
                    shape_match=False,
                    columns_match=True,
                    diff_summary=f"Row count mismatch in order-sensitive query: {cand_rows} vs {gold_rows}",
                    candidate_sample=cand_sample,
                    gold_sample=gold_sample,
                )

            mismatches = 0
            for i, (c_row, g_row) in enumerate(zip(cand_tuples, gold_tuples)):
                if not self._tuples_match(c_row, g_row, expectation.float_tolerance):
                    mismatches += 1

            if mismatches == 0:
                return ExecutionResult(
                    is_executed=True,
                    execution_accuracy=1.0,
                    row_overlap_score=1.0,
                    candidate_row_count=cand_rows,
                    gold_row_count=gold_rows,
                    shape_match=True,
                    columns_match=True,
                    diff_summary="Exact match (order preserved).",
                    candidate_sample=cand_sample,
                    gold_sample=gold_sample,
                )
            else:
                return ExecutionResult(
                    is_executed=True,
                    execution_accuracy=0.0,
                    row_overlap_score=max(0.0, 1.0 - (mismatches / gold_rows)),
                    candidate_row_count=cand_rows,
                    gold_row_count=gold_rows,
                    shape_match=True,
                    columns_match=True,
                    diff_summary=f"Order mismatch: {mismatches}/{gold_rows} rows differed in positional order",
                    candidate_sample=cand_sample,
                    gold_sample=gold_sample,
                )

        # Unordered Multiset / Bag comparison
        matched_gold_indices = set()
        matched_cand_indices = set()

        for c_idx, c_row in enumerate(cand_tuples):
            for g_idx, g_row in enumerate(gold_tuples):
                if g_idx not in matched_gold_indices:
                    if self._tuples_match(c_row, g_row, expectation.float_tolerance):
                        matched_gold_indices.add(g_idx)
                        matched_cand_indices.add(c_idx)
                        break

        missing_count = len(gold_tuples) - len(matched_gold_indices)
        extra_count = len(cand_tuples) - len(matched_cand_indices)
        total_unique = len(gold_tuples) + extra_count
        overlap_score = len(matched_gold_indices) / total_unique if total_unique > 0 else 0.0

        is_exact = (missing_count == 0 and extra_count == 0)

        diff_msg = None
        if not is_exact:
            diff_msg = f"Tabular mismatch: missing {missing_count} expected rows, found {extra_count} extraneous rows"

        return ExecutionResult(
            is_executed=True,
            execution_accuracy=1.0 if is_exact else 0.0,
            row_overlap_score=round(overlap_score, 4),
            candidate_row_count=cand_rows,
            gold_row_count=gold_rows,
            shape_match=(cand_rows == gold_rows and cand_cols == gold_cols),
            columns_match=True,
            missing_rows_count=missing_count,
            extra_rows_count=extra_count,
            diff_summary=diff_msg or "Exact tabular match (order invariant).",
            candidate_sample=cand_sample,
            gold_sample=gold_sample,
        )

    def _normalize_dataframe(self, df: pd.DataFrame, expectation: ExecutionExpectation) -> pd.DataFrame:
        """Clean and normalize DataFrame values for robust comparison."""
        cleaned = df.copy()

        # Positional alignment: normalize column names to integers if needed
        cleaned.columns = [str(c).strip().lower() for c in cleaned.columns]

        for col in cleaned.columns:
            # Handle string whitespace and casing
            if pd.api.types.is_string_dtype(cleaned[col]) or pd.api.types.is_object_dtype(cleaned[col]):
                cleaned[col] = cleaned[col].apply(
                    lambda x: str(x).strip().lower()
                    if (pd.notna(x) and not expectation.case_sensitive_strings)
                    else (str(x).strip() if pd.notna(x) else None)
                )

        return cleaned

    def _row_to_tuple(self, row: pd.Series) -> tuple:
        """Convert a DataFrame row series to a standardized tuple."""
        return tuple(row.values)

    def _tuples_match(self, t1: tuple, t2: tuple, float_tol: float) -> bool:
        """Check if two row tuples match with float tolerance and NULL equivalence."""
        if len(t1) != len(t2):
            return False

        for v1, v2 in zip(t1, t2):
            # 1. Null / None / NaN checks
            is_null1 = pd.isna(v1) or v1 is None
            is_null2 = pd.isna(v2) or v2 is None

            if is_null1 and is_null2:
                continue
            if is_null1 != is_null2:
                return False

            # 2. Numeric comparison with tolerance
            if isinstance(v1, (int, float, np.number)) and isinstance(v2, (int, float, np.number)):
                if not math.isclose(float(v1), float(v2), rel_tol=float_tol, abs_tol=float_tol):
                    return False
            else:
                # 3. String / General equality
                if str(v1).strip() != str(v2).strip():
                    return False

        return True
